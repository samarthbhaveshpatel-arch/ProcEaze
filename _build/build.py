"""
Build the ProcEaze static website.

    python _build/build.py

Writes every page as standalone HTML into the project root using clean
folder URLs (/platform/ -> platform/index.html), plus sitemap.xml,
robots.txt, redirects from the old .html URLs, then checks all internal links.
Serve the output from any static web server; folder URLs need a server
(or a host) that maps /path/ to /path/index.html.
"""
import os
import re
import sys
import shutil
import importlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from lib import CTX, BASE_URL, ROUTES, route, esc
from chrome import page  # noqa: E402

MODULES = ["pages_home", "pages_platform", "pages_software", "pages_services", "pages_solutions",
           "pages_company", "pages_partners", "pages_knowledge", "pages_tools", "pages_misc"]

# Top-level folders that hold generated pages; anything else in OUT is source or assets
KEEP_DIRS = {"_build", "assets", "photos", ".vscode", ".claude", ".git"}


def collect():
    pages = []
    for name in MODULES:
        try:
            mod = importlib.import_module(name)
        except ModuleNotFoundError as e:
            if e.name == name:
                print(f"  (skipping {name}: not written yet)")
                continue
            raise
        pages.extend(mod.PAGES)
    return pages


def out_file(url):
    """File that serves a URL path: 'platform/' -> platform/index.html."""
    return os.path.join(OUT, *(url + "index.html").split("/"))


def render(p):
    url = route(p["path"])
    CTX["root"] = "../" * url.count("/")
    CTX["path"] = p["path"]
    CTX["section"] = p.get("section", "")
    html = page(p["path"], p["title"], p["desc"], p["body"](), crumbs=p.get("crumbs"),
                section=p.get("section", ""), schemas=p.get("schemas"), noindex=p.get("noindex", False),
                og_type=p.get("og_type", "website"), js=p.get("js", ()))
    dest = out_file(url)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(html)
    return dest


# ---------------------------------------------------------------------------
# Redirects from the old .html URLs
# ---------------------------------------------------------------------------
def legacy_routes():
    return [(old, new) for old, new in ROUTES.items() if old.endswith(".html") and old != "index.html"]


def write_redirect_stubs():
    """A tiny page at each old URL that forwards to the new one. Works on any host;
    the .htaccess / _redirects files give a proper 301 where the host supports them."""
    written = []
    for old, new in legacy_routes():
        rel = "../" * old.count("/") + new
        canonical = BASE_URL + "/" + new
        html = (f'<!doctype html>\n<html lang="en-IN"><head><meta charset="utf-8"><title>Page moved | ProcEaze</title>'
                f'<link rel="canonical" href="{canonical}"><meta name="robots" content="noindex, follow">'
                f'<meta http-equiv="refresh" content="0; url={esc(rel)}">'
                f'<script>location.replace({rel!r}+location.search+location.hash)</script></head>'
                f'<body><p>This page has moved to <a href="{esc(rel)}">{canonical}</a>.</p></body></html>\n')
        dest = os.path.join(OUT, *old.split("/"))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8", newline="\n") as f:
            f.write(html)
        written.append(dest)
    return written


def write_server_redirects():
    rules = legacy_routes()
    with open(os.path.join(OUT, ".htaccess"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Apache: permanent redirects from the old .html URLs (generated by _build/build.py)\n"
                "DirectoryIndex index.html\n")
        f.write("".join(f"Redirect 301 /{old} /{new}\n" for old, new in rules))
    with open(os.path.join(OUT, "_redirects"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Netlify / Cloudflare Pages: permanent redirects (generated by _build/build.py)\n")
        f.write("".join(f"/{old}  /{new}  301!\n" for old, new in rules))


# ---------------------------------------------------------------------------
# Sitemap / robots
# ---------------------------------------------------------------------------
def write_sitemap(pages):
    urls = []
    for p in pages:
        if p.get("noindex"):
            continue
        url = route(p["path"])
        prio = "1.0" if url == "" else ("0.9" if url.count("/") == 1 else "0.7")
        urls.append(f"  <url><loc>{BASE_URL}/{url}</loc><changefreq>monthly</changefreq><priority>{prio}</priority></url>")
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
           + "\n".join(urls) + "\n</urlset>\n")
    with open(os.path.join(OUT, "sitemap.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(xml)


def write_robots():
    txt = (
        "# robots.txt for www.proceaze.in (marketing site)\n"
        "# The application at app.proceaze.in is a separate host and must serve its own\n"
        "# robots.txt with 'Disallow: /' and an 'X-Robots-Tag: noindex' header.\n"
        "User-agent: *\n"
        "Allow: /\n"
        "Disallow: /_build/\n\n"
        f"Sitemap: {BASE_URL}/sitemap.xml\n"
    )
    with open(os.path.join(OUT, "robots.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(txt)


# ---------------------------------------------------------------------------
# Checks / cleanup
# ---------------------------------------------------------------------------
LINK_RE = re.compile(r'(?:href|src)="([^"]+)"')
LEGACY = {os.path.normcase(os.path.join(OUT, *old.split("/"))) for old, _ in legacy_routes()}


def check_links(files):
    broken = []
    for path in files:
        with open(path, encoding="utf-8") as f:
            html = f.read()
        ids = set(re.findall(r'id="([^"]+)"', html))
        for url in LINK_RE.findall(html):
            if url.startswith(("http://", "https://", "mailto:", "tel:", "data:")):
                continue
            if url.startswith("#"):
                if len(url) > 1 and url[1:] not in ids:
                    broken.append((path, url))
                continue
            target = url.split("#")[0].split("?")[0]
            full = os.path.normpath(os.path.join(os.path.dirname(path), target))
            if os.path.isdir(full):
                full = os.path.join(full, "index.html")
            if not os.path.exists(full):
                broken.append((path, url))
            elif os.path.normcase(full) in LEGACY:
                broken.append((path, url + "  (old .html URL: link the page key through L())"))
            elif os.path.dirname(path) != OUT and not url.startswith("../"):
                # Pages in sub-folders must link via ../ — anything else was rendered with the wrong root
                broken.append((path, url + "  (missing ../ prefix)"))
    return broken


def remove_stale(keep):
    """Delete generated HTML that no page or redirect produces any more."""
    keep = {os.path.normcase(k) for k in keep}
    for top in os.listdir(OUT):
        full = os.path.join(OUT, top)
        if top in KEEP_DIRS or top.startswith("."):
            continue
        if os.path.isfile(full):
            if top.endswith(".html") and os.path.normcase(full) not in keep:
                os.remove(full)
                print(f"  removed stale {top}")
            continue
        for dirpath, _, files in os.walk(full, topdown=False):
            for fn in files:
                fp = os.path.join(dirpath, fn)
                if fn.endswith(".html") and os.path.normcase(fp) not in keep:
                    os.remove(fp)
                    print(f"  removed stale {os.path.relpath(fp, OUT)}")
            if not os.listdir(dirpath):
                shutil.rmtree(dirpath)


def main():
    pages = collect()
    urls = [route(p["path"]) for p in pages]
    dupes = {x for x in urls if urls.count(x) > 1}
    if dupes:
        sys.exit(f"Duplicate page URLs: {dupes}")
    written = [render(p) for p in pages]
    stubs = write_redirect_stubs()
    remove_stale(written + stubs)
    write_server_redirects()
    write_sitemap(pages)
    write_robots()
    broken = check_links(written)
    print(f"Built {len(written)} pages, {len(stubs)} redirects.")
    if broken:
        print(f"{len(broken)} broken link(s):")
        for f, u in broken:
            print(f"  {os.path.relpath(f, OUT)} -> {u}")
        sys.exit(1)
    print("All internal links resolve.")


if __name__ == "__main__":
    main()
